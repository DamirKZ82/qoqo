"""Единицы измерения из ОКЕИ.

Общероссийский классификатор единиц измерения — тот же справочник, которым
пользуется 1С. Совпадение кодов важно для обмена: единица «килограмм» должна
быть узнана как 166, а не сопоставлена по названию.

Здесь не весь классификатор, а рабочий набор: то, чем измеряют товар и тару в
торговле. Классификатор насчитывает сотни позиций, большинство из которых —
единицы электротехники и физики, и в подборе они только мешали бы. Добавить
недостающую — дописать строку в этот кортеж.
"""

from dataclasses import dataclass


