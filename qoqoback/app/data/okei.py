def search(query: str | None = None) -> list[OkeiUnit]:
    """Единицы, подходящие под запрос. Пустой запрос — весь набор.

    Ищем и по коду, и по обозначению, и по названию: человек помнит либо «166»,
    либо «кг», либо «килограмм», и заставлять его угадывать наш способ поиска
    незачем.
    """

    if not query or not query.strip():
        return list(OKEI)

    текст = query.strip().lower()
    return [
        единица
        for единица in OKEI
        if текст in единица.code or текст in единица.symbol.lower() or текст in единица.name.lower()
    ]
