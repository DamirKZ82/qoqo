/**
 * Предложение браузеру сохранить пароль после входа.
 *
 * Обычную форму браузер запоминает сам: он видит отправку и следом переход на
 * другую страницу и считает вход состоявшимся. У одностраничного приложения
 * перехода нет — запрос уходит в фоне, а страница меняется силами React.
 * Поэтому предложение сохранить пароль не появляется, хотя форма размечена
 * правильно.
 *
 * Прямо об этом браузеру говорит Credential Management API. Поддерживают его
 * не все: в Safari и Firefox его нет, и там остаётся встроенная эвристика.
 * Поэтому вызов необязательный — не поддержали, значит просто ничего не
 * произошло.
 *
 * Пароль при этом не покидает браузер: он уходит в его же хранилище, а не к
 * нам. Сохранять или нет, решает пользователь в своём окне подтверждения.
 */
export async function offerToSavePassword(email: string, password: string): Promise<void> {
  const Ctor = (window as unknown as { PasswordCredential?: new (data: object) => Credential })
    .PasswordCredential

  if (!Ctor || !navigator.credentials?.store) return

  try {
    await navigator.credentials.store(new Ctor({ id: email, password, name: email }))
  } catch {
    // Отказ пользователя, небезопасный контекст, запрет политикой — всё это
    // не должно мешать входу: он уже состоялся.
  }
}
